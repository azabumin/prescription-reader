-- Pharmacy MVP (docs/superpowers/specs/2026-10-26-pharmacy-mvp-design.md).
-- Pharmacies log in with their own password, set once through a one-time setup code that the
-- operator issues (worker/scripts/new-pharmacy.mjs) -- the operator never knows the password.
CREATE TABLE pharmacies (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  code TEXT NOT NULL UNIQUE,            -- public slug in the patient QR (https://rxhelper.jp/send?ph=<code>)
  name TEXT NOT NULL,
  login_email TEXT NOT NULL UNIQUE,
  password_hash TEXT,
  password_salt TEXT,
  setup_code_hash TEXT,                 -- SHA-256 hex of the one-time setup code; NULL once used
  setup_expires_at TEXT,
  created_at TEXT NOT NULL,
  disabled_at TEXT
);

CREATE TABLE pharmacy_sessions (
  token TEXT PRIMARY KEY,
  pharmacy_id INTEGER NOT NULL REFERENCES pharmacies(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL
);

CREATE INDEX idx_pharmacy_sessions_pharmacy_id ON pharmacy_sessions(pharmacy_id);

-- One patient send. Personal data (card_json, drugs_json, notify_email, images, messages) is removed
-- when the pharmacy marks it done; the whole row goes 7 days after created_at (expires_at).
CREATE TABLE intakes (
  id TEXT PRIMARY KEY,
  pharmacy_id INTEGER NOT NULL REFERENCES pharmacies(id) ON DELETE CASCADE,
  client_request_id TEXT NOT NULL,      -- generated by the patient's device; a resend returns the same intake
  patient_token_hash TEXT NOT NULL,     -- SHA-256 hex of the token the patient's device keeps
  lang TEXT NOT NULL,
  pickup TEXT NOT NULL,
  card_json TEXT,
  drugs_json TEXT,
  drugs_status TEXT NOT NULL DEFAULT 'pending', -- 'pending' | 'done' | 'failed'
  notify_email TEXT,
  status TEXT NOT NULL DEFAULT 'new',   -- 'new' | 'ready' | 'inquiry' | 'later' | 'done'
  later_time TEXT,
  created_at TEXT NOT NULL,
  opened_at TEXT,
  replied_at TEXT,
  done_at TEXT,
  expires_at TEXT NOT NULL,
  UNIQUE (pharmacy_id, client_request_id)
);

CREATE INDEX idx_intakes_pharmacy_created ON intakes(pharmacy_id, created_at);
CREATE INDEX idx_intakes_expires ON intakes(expires_at);

-- Prescription photos, kept in D1 (downscaled on the device to ~1600px JPEG) instead of R2.
CREATE TABLE intake_images (
  intake_id TEXT NOT NULL REFERENCES intakes(id) ON DELETE CASCADE,
  idx INTEGER NOT NULL,
  media_type TEXT NOT NULL,
  data_b64 TEXT NOT NULL,
  PRIMARY KEY (intake_id, idx)
);

CREATE TABLE intake_messages (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  intake_id TEXT NOT NULL REFERENCES intakes(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,                   -- 'template' | 'free'
  template_key TEXT,
  text_ja TEXT NOT NULL,
  text_patient TEXT NOT NULL,
  created_at TEXT NOT NULL
);

-- Timing record for the verification study. No personal data: intake_ref is a one-way hash of the
-- intake id, so it survives the 7-day purge without pointing back to anyone.
CREATE TABLE intake_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  pharmacy_id INTEGER NOT NULL,
  intake_ref TEXT NOT NULL,
  event TEXT NOT NULL,                  -- 'received' | 'opened' | 'replied' | 'done' | 'expired'
  lang TEXT,
  drug_count INTEGER,
  at TEXT NOT NULL
);

CREATE INDEX idx_intake_events_pharmacy_at ON intake_events(pharmacy_id, at);
